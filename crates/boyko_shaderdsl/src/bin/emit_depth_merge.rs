//! `emit_depth_merge` — generates the committed SDF depth-merge fragment shader (render wave RD1,
//! defect R0b):
//!
//! ```text
//! sdf_depth_merge.fs.hlsl    full-screen SV_Depth pass: gViewT `t` -> the path's depth encode
//! ```
//!
//! Run: `cargo run -p boyko_shaderdsl --features emit --bin emit_depth_merge`
//!
//! One source, ONE artifact — **no `-D` axis**: Deferred's custom-linear encode and the reverse-Z
//! encode are a push-constant `mode` word (wave-uniform, one branch), because the two arms change
//! no interface. DXC the file with the frozen recipe pinned in its header and commit the `.spv`.
//! `boyko_rhi_vulkan/tests/sdf_depth_merge_edsl_sync.rs` pins the committed `.hlsl` to this
//! template's generated spans, the committed `.spv` to a fresh re-DXC of its source, the leaves to
//! an `f64` reference, and the skeleton's interface.
//!
//! # Why the generator owns the WHOLE file
//!
//! The eDSL has no texture fetch, no push constants and no `discard`, so the skeleton — bindings,
//! push block, the `gViewT` load, the background `discard`, the mode branch, `generate_ray` and
//! the `SV_Depth` return — is hand-written HLSL owned here as a `format!` template (the
//! `emit_ui` / `emit_particles` idiom). The mode words and the bias are GENERATOR INPUTS read from
//! `boyko_shaderdsl::depth`, so no shader spells a number the host push also spells.
//!
//! The ray is generated by the SAME `ray_gen.hlsli` the marchers include (an `#include`, never a
//! pasted copy), so the merge's `rd` and the marcher's `rd` cannot drift apart.
//!
//! The template itself is `boyko_shaderdsl::emit::emit_sdf_depth_merge_fs` (library-side, so the
//! sync test compares the whole committed file to it); this bin only writes it.

use std::path::PathBuf;

use boyko_shaderdsl::depth::{
    SDF_DEPTH_MERGE_BIAS, SDF_DEPTH_MERGE_BIAS_DENOM, SDF_DEPTH_MERGE_MODE_LINEAR,
    SDF_DEPTH_MERGE_MODE_REVERSE_Z,
};
use boyko_shaderdsl::emit;

fn main() {
    // The printed `1.0 / DENOM.0` is the leaf's own value: one number, two spellings that are
    // exact in every precision involved.
    const _: () = assert!(
        SDF_DEPTH_MERGE_BIAS.to_bits() == (1.0 / SDF_DEPTH_MERGE_BIAS_DENOM as f32).to_bits()
    );
    const _: () = assert!(SDF_DEPTH_MERGE_MODE_LINEAR != SDF_DEPTH_MERGE_MODE_REVERSE_Z);

    let out = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("boyko_rhi_vulkan")
        .join("shaders")
        .join("sdf_depth_merge.fs.hlsl");
    let text = emit::emit_sdf_depth_merge_fs();
    std::fs::write(&out, &text)
        .unwrap_or_else(|e| panic!("invariant: failed to write {} : {e}", out.display()));
    println!("wrote {} ({} bytes)", out.display(), text.len());
}
