//! `emit_ui` — generates BOTH committed UI-rect shaders (`docs/UI-PLAN-SPRITES.md` rung S1,
//! architecture D30):
//!
//! ```text
//! ui_rect.vs.hlsl    the vertexless unit-quad expansion + pixel->NDC ortho
//! ui_rect.fs.hlsl    rounded-box SDF + AA + uniform border + MSDF text + flag-gated clip
//! ```
//!
//! Run: `cargo run -p boyko_shaderdsl --features emit --bin emit_ui`
//!
//! Two sources, TWO artifacts — **no `-D` axis** (each source compiles to exactly one `.spv`;
//! the rows in `docs/SHADER-VARIANT-MANIFEST.md` state that). DXC each file with the frozen
//! recipe pinned in its own header and commit the `.spv`.
//! `boyko_render/tests/ui_rect_edsl_sync.rs` pins the committed `.hlsl` to these templates'
//! generated spans, and `boyko_render/tests/ui_rect_spv_sync.rs` pins each committed `.spv` to
//! a fresh re-DXC of its source.
//!
//! # Why the generator owns the WHOLE file (the `emit_particles` F13/F14 idiom)
//!
//! The eDSL has no texture sampling, no interpolator plumbing and no push constants, so the
//! skeleton — bindings, `VsOut`, `[[vk::push_constant]]`, `main` — is hand-written HLSL owned
//! here as a `format!` template. Owning it here is what keeps that glue single-sourced with
//! the eDSL spans it wraps AND with the numbers below: the `UiInstance` field offsets, the
//! stride and the three flag-bit indices are GENERATOR INPUTS (`UiInstanceLayout`), so no
//! shader ever spells a byte offset that a host `offset_of!` also spells (S-D10).
//! `ui_rect_edsl_sync` re-derives the layout from the HOST `UiInstance` and pins the committed
//! mirror span to it — the literals below cannot silently drift from the Rust struct.
//!
//! # What is NOT generated
//!
//! The host-side pipeline/layout creation (`boyko_render::ui::resources`) and the two
//! recorders; each stage's (set, binding, kind) table is spelled in its own skeleton and the
//! host's must match it.

use std::path::PathBuf;

use boyko_shaderdsl::emit::{self, UiInstanceLayout};

// ---- Generator inputs (mirrored host-side; S-D10) ------------------------------------------

/// The `UiInstance` byte layout — MIRRORS `boyko_render::ui::instance` (`#[repr(C, align(16))]`,
/// 80 B since the UI-ADVANCED S2 widening, per-field `offset_of!` const-asserts).
/// `ui_rect_edsl_sync::ui_instance_mirror_matches_host` re-derives every number from the host
/// struct and pins the committed span, so a drift on either side is a red test, not a silent
/// skew.
const UI_INSTANCE_LAYOUT: UiInstanceLayout = UiInstanceLayout {
    size: 80,
    min_px: 0,
    size_px: 8,
    clip: 16,
    corner_radius: 32,
    uv: 48,
    color: 64,
    border_color: 68,
    border_width: 72,
    flags: 76,
    flag_border_any_bit: 0,
    flag_clip_present_bit: 1,
    flag_text_bit: 2,
    flag_textured_bit: 3,
    slot_shift: 20,
    slot_bits: 12,
};

/// Wraps a generated BODY span in its sentinel pair + doc comment + signature + closing brace.
///
/// The sentinels enclose the WHOLE function (doc + signature + body + `}`) — the
/// `emit_particles` layout, which is what `ui_rect_edsl_sync`'s `extract_fn` + span-containment
/// pin assumes.
fn leaf(name: &str, doc: &str, sig: &str, body: &str) -> String {
    format!(
        "// === GENERATED {name} BEGIN ===\n{doc}{sig} {{\n{body}}}\n// === GENERATED {name} END ===\n"
    )
}

fn build_vs() -> String {
    let mirror = emit::emit_hlsl_ui_instance_mirror(&UI_INSTANCE_LAYOUT);
    format!(
        r#"// GUI P5a UI-rect vertex shader (`ui_rect.vs.hlsl`): a vertexless unit quad whose
// corner positions come from SV_VertexID and whose per-instance transform is read
// from a StructuredBuffer<UiInstance> (set 0, binding 0, STORAGE, VERTEX|FRAGMENT)
// by SV_InstanceID -- the combination proven by the Rung-0.5 GPU golden.
//
// GENERATED by `cargo run -p boyko_shaderdsl --features emit --bin emit_ui` (UI-ADVANCED S1).
// The `// === GENERATED <name> BEGIN/END ===` span is MACHINE-EMITTED; a hand-edit fails
// `boyko_render/tests/ui_rect_edsl_sync.rs`, and the committed `.spv` is byte-gated by
// `boyko_render/tests/ui_rect_spv_sync.rs`.
//
// The VS transforms the quad into NDC by a 2D pixel->NDC ortho push constant
// (top-left origin via a POSITIVE y scale, Vulkan y-down NDC -- see UiOrtho), and
// forwards the physical-px fragment position + the instance index to the FS, which
// evaluates the rounded-box SDF + AA + uniform border + flag-gated clip.
//
// Compiled offline (hermetic build -- no SDK at `cargo build` time) with:
//   C:\VulkanSDK\1.4.350.0\Bin\dxc.exe -spirv -T vs_6_0 -E main \
//       -fspv-target-env=vulkan1.3 ui_rect.vs.hlsl -Fo ui_rect.vs.spv

// === GENERATED ui_instance_mirror BEGIN ===
{mirror}// === GENERATED ui_instance_mirror END ===

[[vk::binding(0, 0)]] StructuredBuffer<UiInstance> g_instances : register(t0);

// pixel -> NDC ortho (UiOrtho): ndc = pos_px * scale + translate. 16 bytes.
struct Ortho {{
    float2 scale;
    float2 translate;
}};
[[vk::push_constant]] Ortho g_ortho;

static const float2 CORNERS[6] = {{
    float2(0.0, 0.0),
    float2(1.0, 0.0),
    float2(0.0, 1.0),
    float2(0.0, 1.0),
    float2(1.0, 0.0),
    float2(1.0, 1.0),
}};

struct VsOut {{
    float4 position  : SV_Position;
    float2 pos_px    : TEXCOORD0;   // physical px, for the FS clip test
    float2 local_px  : TEXCOORD1;   // rect-centred px, for the SDF
    float2 local_uv  : TEXCOORD2;   // GUI P5b (Decision T4-B): the 0..1 quad corner;
                                    // the FS text branch lerps the glyph UV with it
    nointerpolation uint inst_index : INSTANCE;
}};

VsOut main(uint vid : SV_VertexID, uint iid : SV_InstanceID) {{
    UiInstance inst = g_instances[iid];                 // SSBO read in the VERTEX stage
    float2 corner = CORNERS[vid];
    float2 pos_px = inst.min_px + corner * inst.size_px;

    VsOut o;
    o.position   = float4(pos_px * g_ortho.scale + g_ortho.translate, 0.0, 1.0);
    o.pos_px     = pos_px;
    o.local_px   = pos_px - (inst.min_px + 0.5 * inst.size_px); // rect-centred
    o.local_uv   = corner;          // 0..1 within the quad (rect branch ignores it)
    o.inst_index = iid;
    return o;
}}
"#
    )
}

fn build_fs() -> String {
    let mirror = emit::emit_hlsl_ui_instance_mirror(&UI_INSTANCE_LAYOUT);
    let flags = emit::emit_hlsl_ui_flag_consts(&UI_INSTANCE_LAYOUT);

    let unpack = leaf(
        "ui_unpack_rgba8",
        "// Unpack a premultiplied RGBA8 (byte0=R..byte3=A) to a float4 in [0,1]\n\
         // (`boyko_shaderdsl::ui::ui_unpack_rgba8_body`).\n",
        "float4 ui_unpack_rgba8(uint c)",
        &emit::emit_hlsl_ui_unpack_rgba8(),
    );
    let sd = leaf(
        "ui_sd_rounded_box",
        "// Quilez/Bevy per-corner rounded-box SDF (`boyko_shaderdsl::ui::ui_sd_rounded_box_body`).\n\
         // `p` is rect-centred; `half_size` is half the rect; `r` is (tl, tr, br, bl). Selects\n\
         // the corner radius by the quadrant of p.\n",
        "float ui_sd_rounded_box(float2 p, float2 half_size, float4 r)",
        &emit::emit_hlsl_ui_sd_rounded_box(),
    );
    let clip = leaf(
        "ui_clip_coverage",
        "// Anti-aliased coverage of a finite clip AABB at physical-px `pos`\n\
         // (`boyko_shaderdsl::ui::ui_clip_coverage_body`). 1 inside, 0 outside, a ~1px AA band\n\
         // at the edges (so a clipped edge is as crisp as a rect edge). `clip` is\n\
         // (min.xy, max.xy), always finite when CLIP_PRESENT is set.\n",
        "float ui_clip_coverage(float2 pos, float4 clip, float fw)",
        &emit::emit_hlsl_ui_clip_coverage(),
    );
    let median = leaf(
        "ui_median3",
        "// GUI P5b MSDF reconstruction (canonical Chlumsky; `boyko_shaderdsl::ui::ui_median3_body`).\n\
         // The per-channel median recovers the sharp signed distance; corners are preserved\n\
         // because the three channels disagree only across a true edge.\n",
        "float ui_median3(float r, float g, float b)",
        &emit::emit_hlsl_ui_median3(),
    );
    let range = leaf(
        "ui_screen_px_range",
        "// Converts the baked TEXEL distance range into a SCREEN-px range at this fragment\n\
         // (`boyko_shaderdsl::ui::ui_screen_px_range_body`), so the AA band is ~1 device px\n\
         // regardless of glyph scale. `fwidth(uv) == 0` on a flat run gives `screenTexSz == Inf`;\n\
         // `max(..., 1.0)` floors it (the NaN/Inf guard).\n",
        "float ui_screen_px_range(float2 uv)",
        &emit::emit_hlsl_ui_screen_px_range(),
    );
    let over = leaf(
        "ui_premultiplied_over",
        "// Premultiplied \"over\" (`boyko_shaderdsl::ui::ui_premultiplied_over_body`): composite\n\
         // the border ring (premultiplied color `bc`, area-weighted by `border_cov`) ON TOP of\n\
         // the fill restricted to the inner shape (`fill * inner_cov`). Where the ring is\n\
         // translucent (bc.a < 1) the fill shows through via the (1 - src_a) term -- a `lerp`\n\
         // of two premultiplied colors would mis-weight that fall-through.\n\
         //   result = src + dst * (1 - src_alpha)\n",
        "float4 ui_premultiplied_over(float4 bc, float border_cov, float4 fill, float inner_cov)",
        &emit::emit_hlsl_ui_premultiplied_over(),
    );

    format!(
        r#"// GUI P5a UI-rect fragment shader (`ui_rect.fs.hlsl`): a rounded-box SDF + AA +
// UNIFORM border + flag-gated in-shader clip, output PREMULTIPLIED (matches the
// engine's src=ONE premultiplied-alpha blend).
//
// GENERATED by `cargo run -p boyko_shaderdsl --features emit --bin emit_ui` (UI-ADVANCED S1).
// The `// === GENERATED <name> BEGIN/END ===` spans are MACHINE-EMITTED from
// `boyko_shaderdsl::ui`'s generic `C: Cf` leaves; a hand-edit fails
// `boyko_render/tests/ui_rect_edsl_sync.rs`, and the committed `.spv` is byte-gated by
// `boyko_render/tests/ui_rect_spv_sync.rs`. The `f32` Eval instantiation of the SAME
// leaves is the CPU oracle `boyko_shaderdsl/tests/ui_leaves.rs` pins.
//
// The record is re-read from the same StructuredBuffer<UiInstance> by the
// interpolated SV_InstanceID (the FRAGMENT-stage SSBO read proven by Rung 0.5).
// All math is in physical px (the VS forwards rect-centred local_px), so fwidth(d)
// is one device-pixel wide AA -- DPI-correct under the Decision-9 full-extent
// contract (the UI viewport spans the same pixels the ortho denominator uses).
//
// Compiled offline (hermetic build -- no SDK at `cargo build` time) with:
//   C:\VulkanSDK\1.4.350.0\Bin\dxc.exe -spirv -T ps_6_0 -E main \
//       -fspv-target-env=vulkan1.3 ui_rect.fs.hlsl -Fo ui_rect.fs.spv

// === GENERATED ui_instance_mirror BEGIN ===
{mirror}// === GENERATED ui_instance_mirror END ===

[[vk::binding(0, 0)]] StructuredBuffer<UiInstance> g_instances : register(t0);

// GUI P5b (Decision T4-G/T4-A): the MSDF glyph atlas (binding 1, a combined
// image+sampler, FRAGMENT-visible) + the per-atlas uniform (binding 2): the baked
// distance range in TEXELS and the atlas size in texels. The atlas is upload-once,
// all-FIF sample concurrently (SampledComposite); the UBO is written once at upload
// and is immutable (one atlas -> one constant pxRange/size). Both bindings are present
// for EVERY draw but only sampled in the FLAG_TEXT branch, so the rect path is free.
[[vk::binding(1, 0)]] Texture2D    g_atlas         : register(t1);
[[vk::binding(1, 0)]] SamplerState g_atlas_sampler : register(s1);
struct AtlasUniform {{
    float px_range;     // = AtlasMeta.distance_range_texels (the screenPxRange divisor)
    float _pad0;
    float2 atlas_size;  // (atlas_w, atlas_h) in texels
}};
[[vk::binding(2, 0)]] ConstantBuffer<AtlasUniform> g_atlas_ubo : register(b2);

// UI-ADVANCED S3 -- the SPRITE lane's two declarations (architecture D2 + S-D3 + S-D4).
//
// Set 1, binding 0 is the SHARED bindless texture array (`BindlessTextureTable`, capacity
// 4096) -- the SAME set the textured gbuffer / Forward / particle paths bind, declared here
// character-for-character as `particle_draw.fs.hlsl` declares it. The UI declares ONLY that
// binding of set 1: it samples through its OWN sampler below, never through the set's shared
// immutable sampler (trilinear + 16x anisotropic + REPEAT), which was chosen for tiled world
// material textures and would foreclose a pixel-art UI forever (S-D4).
[[vk::binding(0, 1)]] Texture2D g_sprites[] : register(t0, space1);

// The UI's OWN sprite sampler (set 0, binding 3): the filter mode is chosen once at
// `ui_setup` (`UiSamplerMode::{{Smooth, Pixel}}` -> LINEAR/ClampToEdge vs NEAREST/ClampToEdge),
// so NEAREST pixel art is expressible without touching the world-shared bindless set (which
// D3 refuses to let a UI concern mutate). The host binds a COMBINED_IMAGE_SAMPLER there and
// this stage reads only its SAMPLER half -- the same separate-image/separate-sampler shape
// binding 1 above already uses for the atlas, and the mechanism gate G3-0 measured.
[[vk::binding(3, 0)]] SamplerState g_ui_sampler : register(s3);

struct VsOut {{
    float4 position  : SV_Position;
    float2 pos_px    : TEXCOORD0;
    float2 local_px  : TEXCOORD1;
    float2 local_uv  : TEXCOORD2;   // GUI P5b: the 0..1 quad corner (Decision T4-B)
    nointerpolation uint inst_index : INSTANCE;
}};

// === GENERATED ui_flag_consts BEGIN ===
{flags}// === GENERATED ui_flag_consts END ===

{unpack}
{sd}
{clip}
{median}
{range}
{over}
float4 main(VsOut input) : SV_Target0 {{
    UiInstance inst = g_instances[input.inst_index];     // SSBO read in the FRAGMENT stage

    // GUI P5b text branch (Decision T4-G): a uniform-per-instance branch (every
    // fragment of one glyph takes the same side), so the rect majority is unregressed.
    // The glyph's normalized atlas UV rect lives in the record's OWN `uv` field
    // (UI-ADVANCED S2 -- the corner_radius alias is retired).
    if ((inst.flags & FLAG_TEXT) != 0u) {{
        float2 uv  = lerp(inst.uv.xy, inst.uv.zw, input.local_uv);
        float4 msd = g_atlas.Sample(g_atlas_sampler, uv);   // RGBA8 MTSDF (rgb = MSDF)
        float  sd  = ui_median3(msd.r, msd.g, msd.b);
        float  cov = clamp(ui_screen_px_range(uv) * (sd - 0.5) + 0.5, 0.0, 1.0);

        float4 result = ui_unpack_rgba8(inst.color) * cov;  // PREMULTIPLIED fg, weighted
        if ((inst.flags & FLAG_CLIP_PRESENT) != 0u) {{
            float fw = max(fwidth(input.pos_px.x), 1e-5);   // a device-px AA clip band
            result *= ui_clip_coverage(input.pos_px, inst.clip, fw);
        }}
        return result;                                      // PREMULTIPLIED (src=ONE)
    }}

    // UI-ADVANCED S3 sprite branch (architecture D2 / D8e): a bindless-indexed textured
    // quad. Uniform-per-instance like the text branch above (every fragment of one sprite
    // takes the same side), so the rect majority is unregressed. The slot rides `flags`
    // bits UI_SLOT_SHIFT..+12 (S-D2).
    //
    // `NonUniformResourceIndex` is REQUIRED INSURANCE, not an observed necessity here. The
    // descriptor index is per INSTANCE, and dropping the qualifier was measured on an RTX
    // 3060 (S3, red mutation M3-b) over 256 dense 4x4 quads on 64 distinct slots: every
    // quad still sampled its own texture, because that rasterizer does not pack one warp
    // from two primitives, so the index is wave-uniform by construction -- the same fact
    // that made the plan's 10.1 divergence measurement come out flat. A non-uniform index
    // WITHOUT the qualifier is undefined behaviour by the Vulkan spec, and another driver
    // may pack warps differently, so it stays (risk SR3).
    if ((inst.flags & FLAG_TEXTURED) != 0u) {{
        uint   slot = (inst.flags >> UI_SLOT_SHIFT) & UI_SLOT_MASK;
        float2 uv   = lerp(inst.uv.xy, inst.uv.zw, input.local_uv);
        float4 t    = g_sprites[NonUniformResourceIndex(slot)].Sample(g_ui_sampler, uv);

        // The sprite source is STRAIGHT RGBA8; premultiply it, then MODULATE by the
        // already-premultiplied tint. Component-wise multiply of two premultiplied colors
        // is the correct tint here: (src.rgb*src.a) * (c.rgb*c.a) == (src.rgb*c.rgb) *
        // (src.a*c.a), which is the premultiplied form of the straight-space product.
        float4 result = float4(t.rgb * t.a, t.a) * ui_unpack_rgba8(inst.color);
        if ((inst.flags & FLAG_CLIP_PRESENT) != 0u) {{
            float fw = max(fwidth(input.pos_px.x), 1e-5);   // a device-px AA clip band
            result *= ui_clip_coverage(input.pos_px, inst.clip, fw);
        }}
        return result;                                      // PREMULTIPLIED (src=ONE)
    }}

    float2 half_size = 0.5 * inst.size_px;

    float d  = ui_sd_rounded_box(input.local_px, half_size, inst.corner_radius);
    float fw = max(fwidth(d), 1e-5);                      // resolution-independent AA
    float fill_cov = 1.0 - smoothstep(-fw, fw, d);       // outer-shape coverage

    // `inst.color` is PREMULTIPLIED RGBA8. ui_unpack_rgba8 yields a premultiplied
    // float4 (rgb already carries the * a factor); `result` accumulates the final
    // premultiplied pixel.
    float4 result = ui_unpack_rgba8(inst.color) * fill_cov;  // fill, area-weighted
    // UNIFORM border (P5a exact): the inner shape is the same rounded box inset by
    // the border width; the ring between outer and inner is the border color, drawn
    // OVER the fill in PREMULTIPLIED space (ui_premultiplied_over).
    if ((inst.flags & FLAG_BORDER_ANY) != 0u) {{
        float bw = inst.border_width;
        float4 inner_r = max(inst.corner_radius - bw, 0.0);
        float d_inner = ui_sd_rounded_box(input.local_px, half_size - bw, inner_r);
        float inner_cov = 1.0 - smoothstep(-fw, fw, d_inner);
        float border_cov = saturate(fill_cov - inner_cov);    // exact ring (uniform)

        result = ui_premultiplied_over(ui_unpack_rgba8(inst.border_color), border_cov,
                                       ui_unpack_rgba8(inst.color), inner_cov);
    }}

    if ((inst.flags & FLAG_CLIP_PRESENT) != 0u) {{        // well-predicted uniform branch
        result *= ui_clip_coverage(input.pos_px, inst.clip, fw);
    }}

    // PREMULTIPLIED output (rgb already carries * a; coverage already folded in).
    return result;
}}
"#
    )
}

fn main() {
    // Compile-time guards on the generator's own inputs: a mis-set constant would silently
    // produce a mirror no host `offset_of!` agrees with (the sync test would then red, but a
    // guard here fails FIRST, at generation).
    const _: () = assert!(UI_INSTANCE_LAYOUT.size.is_multiple_of(16));
    const _: () = assert!(UI_INSTANCE_LAYOUT.flags < UI_INSTANCE_LAYOUT.size);
    const _: () = assert!(UI_INSTANCE_LAYOUT.flag_text_bit < 32);

    let shaders = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("boyko_render")
        .join("shaders");

    let files: [(&str, String); 2] = [
        ("ui_rect.vs.hlsl", build_vs()),
        ("ui_rect.fs.hlsl", build_fs()),
    ];

    for (name, text) in &files {
        let out = shaders.join(name);
        std::fs::write(&out, text)
            .unwrap_or_else(|e| panic!("invariant: failed to write {} : {e}", out.display()));
        println!("wrote {} ({} bytes)", out.display(), text.len());
    }
    println!(
        "generator inputs: UiInstance stride {} B, flags @{} (bits {}/{}/{})",
        UI_INSTANCE_LAYOUT.size,
        UI_INSTANCE_LAYOUT.flags,
        UI_INSTANCE_LAYOUT.flag_border_any_bit,
        UI_INSTANCE_LAYOUT.flag_clip_present_bit,
        UI_INSTANCE_LAYOUT.flag_text_bit,
    );
}
