//! generic field / control-flow bodies over the `Emit` / `EmitCf` backends into HLSL.
//!
//! Split out of `emit.rs` (pure structural move); re-exported at the original
//! `crate::emit::emit_hlsl_*` path by `pub use shaders::*` in the parent module
//! ([`super`]). `use super::*` surfaces every private engine helper (`trace`,
//! `Names`, the `NO_*` input consts, `emit_normal_body`, `print_block`, …) these
//! emitters call.

use super::*;

