/// The material-slot color space a decoded texture's samples are encoded in
/// (textured-PBR T2 Decision D2). Decides the GPU image/view format pair — see
/// [`Self::formats`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum ColorSpace {
    /// sRGB-encoded samples (albedo, emissive): the sampler decodes sRGB→linear in
    /// hardware on every read. The common default for a color texture.
    #[default]
    Srgb,
    /// Linear-encoded samples (normal maps, metallic-roughness, AO, ORM masks): no
    /// hardware decode — the raw byte value IS the linear sample.
    Linear,
}

impl ColorSpace {
    /// Maps to the `(image format, view format)` pair [`upload_texture_2d`] /
    /// [`TextureDesc`] need. [`Self::Srgb`] returns
    /// `(R8G8B8A8Unorm, Some(R8G8B8A8Srgb))` (the mutable-view trick); [`Self::Linear`]
    /// returns `(R8G8B8A8Unorm, None)` (image and view share one format).
    #[inline]
    pub const fn formats(self) -> (Format, Option<Format>) {
        match self {
            ColorSpace::Srgb => (Format::R8G8B8A8Unorm, Some(Format::R8G8B8A8Srgb)),
            ColorSpace::Linear => (Format::R8G8B8A8Unorm, None),
        }
    }
}

/// The full mip-chain level count for a `width`x`height` texture:
/// `floor(log2(max(width, height))) + 1`. E.g. `mip_levels_for(8, 8) == 4`
/// (8 → 4 → 2 → 1), `mip_levels_for(1, 1) == 1`.
///
/// # Panics (debug)
/// `width`/`height` must both be `> 0` (a `debug_assert!`; `leading_zeros` on `0`
/// would otherwise make this return `0`, an invalid mip count).
#[inline]
pub const fn mip_levels_for(width: u32, height: u32) -> u32 {
    debug_assert!(width > 0 && height > 0, "invariant: texture extent must be non-zero");
    let max_dim = if width > height { width } else { height };
    // `floor(log2(max_dim)) + 1`, valid for `max_dim >= 1` (checked above).
    32 - max_dim.leading_zeros()
}

/// Builds a `width`x`height` `mip_levels`-level texture (`format` image,
/// `view_format` decoupled SAMPLED view — [`ColorSpace::formats`]), stages
/// `rgba8` (tightly-packed level-0 RGBA8) into mip 0, and — when `mip_levels > 1`
/// — generates the remaining levels via a LINEAR-filtered blit chain on the
/// UNORM image (T2 Decision D3), finishing every level in
/// `ShaderReadOnlyOptimal`. Generalizes
/// [`upload_solid_pixels`](crate::bindless)'s single-mip 2-barrier staged upload
/// (kept untouched, byte-identical, for [`create_solid_color_texture`](crate::bindless::create_solid_color_texture))
/// with an interleaved barrier/blit/barrier chain when `mip_levels > 1`.
///
/// On any partial failure every object created so far is torn down before the
/// error returns (no leak) — mirrors [`create_solid_color_texture`](crate::bindless::create_solid_color_texture).
pub fn upload_texture_2d(
    ctx: &VulkanContext,
    width: u32,
    height: u32,
    rgba8: &[u8],
    format: Format,
    view_format: Option<Format>,
    mip_levels: u32,
) -> Result<VulkanTexture, VulkanError> {
    debug_assert!(width > 0 && height > 0, "invariant: texture extent is non-zero");
    debug_assert!(mip_levels >= 1, "invariant: mip_levels must be >= 1");
    debug_assert_eq!(
        rgba8.len(),
        (width as usize) * (height as usize) * 4,
        "invariant: rgba8 must be exactly width * height * 4 bytes"
    );

    // A blit needs the source mip in TRANSFER_SRC — only required when a mip chain
    // is actually generated (`mip_levels > 1`); the single-mip path stays exactly
    // `SAMPLED | TRANSFER_DST`, matching every pre-T2 texture's usage.
    let usage = if mip_levels > 1 {
        ImageUsage::SAMPLED | ImageUsage::TRANSFER_DST | ImageUsage::TRANSFER_SRC
    } else {
        ImageUsage::SAMPLED | ImageUsage::TRANSFER_DST
    };

    let texture = ctx.create_texture(&TextureDesc {
        width,
        height,
        depth: 1,
        format,
        dimension: TextureDimension::D2,
        usage,
        array_layers: 1,
        mip_levels,
        view_format,
    })?;

    if let Err(e) = upload_mipped_pixels(ctx, &texture, width, height, rgba8, mip_levels) {
        // SAFETY: `texture` was just created on `ctx`, owned exclusively here, and
        // the upload's own submit (if any ran) is fence-waited internally before
        // this error could surface; destroy it once on this edge.
        unsafe { ctx.destroy_texture(texture) };
        return Err(e);
    }
    Ok(texture)
}

/// The staged upload + mip-chain-blit submit for [`upload_texture_2d`] (T2 Decision
/// D3, steps 1-5): stage level-0 pixels → barrier all mips UNDEFINED→TRANSFER_DST →
/// copy level 0 → (per mip `i` in `1..mip_levels`: barrier mip `i-1` TRANSFER_DST→
/// TRANSFER_SRC, LINEAR blit `i-1`→`i`, barrier mip `i-1`→SHADER_READ_ONLY) → barrier
/// the last mip TRANSFER_DST→SHADER_READ_ONLY → one fenced submit + wait.
fn upload_mipped_pixels(
    ctx: &VulkanContext,
    texture: &VulkanTexture,
    width: u32,
    height: u32,
    rgba8: &[u8],
    mip_levels: u32,
) -> Result<(), VulkanError> {
    let size = rgba8.len() as u64;
    let staging = ctx.create_buffer(&BufferDesc {
        size,
        usage: BufferUsage::TRANSFER_SRC,
        location: MemoryLocation::HostVisibleCoherent,
    })?;
    let Some(dst) = ctx.buffer_mapped_ptr(&staging) else {
        // SAFETY: `staging` was just created, never submitted; destroy it once on
        // this edge.
        unsafe { ctx.destroy_buffer(staging) };
        return Err(VulkanError::Unsupported("staging buffer not host-mapped"));
    };
    // SAFETY: `dst` is the persistently-mapped first byte of the host-coherent
    // staging buffer (exactly `size` bytes, just created); `rgba8` is a distinct,
    // non-overlapping allocation of `size` bytes; this is the unique writer before
    // any submission binds the buffer. Host-coherent ⇒ no flush.
    unsafe {
        core::ptr::copy_nonoverlapping(rgba8.as_ptr(), dst.as_ptr(), rgba8.len());
    }

    let mut encoder = match ctx.create_command_encoder() {
        Ok(e) => e,
        Err(e) => {
            // SAFETY: `staging` was just created, never submitted; destroy once.
            unsafe { ctx.destroy_buffer(staging) };
            return Err(e);
        }
    };
    let fence = match ctx.create_fence(false) {
        Ok(f) => f,
        Err(e) => {
            // SAFETY: `encoder`/`staging` were just created, never submitted;
            // destroy each once.
            unsafe {
                ctx.destroy_command_encoder(encoder);
                ctx.destroy_buffer(staging);
            }
            return Err(e);
        }
    };

    let level0_region = [BufferImageCopy {
        buffer_offset: 0,
        buffer_row_length: 0,
        buffer_image_height: 0,
        aspect: ImageAspect::COLOR,
        mip_level: 0,
        base_array_layer: 0,
        layer_count: 1,
        image_offset_x: 0,
        image_offset_y: 0,
        image_offset_z: 0,
        image_extent_w: width,
        image_extent_h: height,
        image_extent_d: 1,
    }];

    let mip_range = |base_mip_level: u32| ImageSubresourceRange {
        aspect: ImageAspect::COLOR,
        base_mip_level,
        level_count: 1,
        base_array_layer: 0,
        layer_count: 1,
    };

    let record = (|| -> Result<(), VulkanError> {
        encoder.begin()?;

        // Step 2: every mip UNDEFINED → TRANSFER_DST_OPTIMAL, then copy level 0.
        encoder.image_barrier(&ImageBarrierDesc {
            texture,
            src_stage: BarrierStage::TOP_OF_PIPE,
            dst_stage: BarrierStage::TRANSFER,
            src_access: BarrierAccess::NONE,
            dst_access: BarrierAccess::TRANSFER_WRITE,
            old_layout: ImageLayout::Undefined,
            new_layout: ImageLayout::TransferDstOptimal,
            range: ImageSubresourceRange {
                aspect: ImageAspect::COLOR,
                base_mip_level: 0,
                level_count: mip_levels,
                base_array_layer: 0,
                layer_count: 1,
            },
        });
        encoder.copy_buffer_to_image(
            &staging,
            texture,
            ImageLayout::TransferDstOptimal,
            &level0_region,
        );

        // Step 3: the mip chain — each level blit-downsampled from the previous.
        for level in 1..mip_levels {
            let src_w = (width >> (level - 1)).max(1);
            let src_h = (height >> (level - 1)).max(1);
            let dst_w = (width >> level).max(1);
            let dst_h = (height >> level).max(1);

            // Source mip TRANSFER_DST → TRANSFER_SRC (it was just written: either the
            // staged copy for level 1's source == mip 0, or the previous iteration's blit).
            encoder.image_barrier(&ImageBarrierDesc {
                texture,
                src_stage: BarrierStage::TRANSFER,
                dst_stage: BarrierStage::TRANSFER,
                src_access: BarrierAccess::TRANSFER_WRITE,
                dst_access: BarrierAccess::TRANSFER_READ,
                old_layout: ImageLayout::TransferDstOptimal,
                new_layout: ImageLayout::TransferSrcOptimal,
                range: mip_range(level - 1),
            });

            encoder.blit_image(&ImageBlitDesc {
                texture,
                aspect: ImageAspect::COLOR,
                src_mip_level: level - 1,
                src_extent_w: src_w,
                src_extent_h: src_h,
                src_layout: ImageLayout::TransferSrcOptimal,
                dst_mip_level: level,
                dst_extent_w: dst_w,
                dst_extent_h: dst_h,
                dst_layout: ImageLayout::TransferDstOptimal,
            });

            // The source mip is now done being read — TRANSFER_SRC → SHADER_READ_ONLY
            // (sample-ready; this level will never be written again).
            encoder.image_barrier(&ImageBarrierDesc {
                texture,
                src_stage: BarrierStage::TRANSFER,
                dst_stage: BarrierStage::FRAGMENT_SHADER,
                src_access: BarrierAccess::TRANSFER_READ,
                dst_access: BarrierAccess::SHADER_READ,
                old_layout: ImageLayout::TransferSrcOptimal,
                new_layout: ImageLayout::ShaderReadOnlyOptimal,
                range: mip_range(level - 1),
            });
        }

        // Step 4: the LAST mip (still TRANSFER_DST — either the level-0 copy when
        // `mip_levels == 1`, or the final blit's destination) → SHADER_READ_ONLY.
        encoder.image_barrier(&ImageBarrierDesc {
            texture,
            src_stage: BarrierStage::TRANSFER,
            dst_stage: BarrierStage::FRAGMENT_SHADER,
            src_access: BarrierAccess::TRANSFER_WRITE,
            dst_access: BarrierAccess::SHADER_READ,
            old_layout: ImageLayout::TransferDstOptimal,
            new_layout: ImageLayout::ShaderReadOnlyOptimal,
            range: mip_range(mip_levels - 1),
        });

        encoder.end()?;
        let queue = ctx.rhi_queue();
        queue.submit(&encoder, &fence)?;
        ctx.wait_fence(&fence, u64::MAX)?;
        Ok(())
    })();

    // Tear down the setup-class transients. The submit (if it ran) is
    // fence-waited above.
    // SAFETY: `encoder`/`fence`/`staging` were created on `ctx`; the encoder's
    // only submission (if any) completed (fence-waited above on the Ok path, or
    // never submitted on an error path), and each is moved by value ⇒ destroyed
    // once.
    unsafe {
        ctx.destroy_command_encoder(encoder);
        ctx.destroy_fence(fence);
        ctx.destroy_buffer(staging);
    }
    record
}

/// Format-generic, single-mip staged upload (AA campaign Stage 2 — the SMAA LUT sibling of
/// [`upload_texture_2d`], which hardcodes RGBA8 4B/px + a mip-blit chain and cannot ingest the
/// SMAA `AreaTex`/`SearchTex` LUTs' `R8G8`/`R8` formats). Builds a `w`x`h` `SAMPLED |
/// TRANSFER_DST` texture at `format`, stages `bytes` into mip 0 via a single fenced
/// staged-upload submit (forks [`crate::bindless::create_solid_color_texture`]'s
/// `upload_solid_pixels` shape, generalized to an arbitrary format + caller-supplied byte
/// buffer instead of a repeated solid fill), and finishes `ShaderReadOnlyOptimal` — the
/// texture is sample-ready before this call returns (no per-frame LUT barrier is ever
/// needed).
///
/// `bytes_per_pixel` is derived from `format`: `R8Unorm` → 1, `R8G8Unorm` → 2,
/// `R8G8B8A8Unorm` → 4. Any other format is `debug_assert`-unreachable (this seam is used
/// ONLY by the boot-time LUT uploads today) and returns [`VulkanError::Unsupported`] in
/// release, rather than silently misreading `bytes`' length.
///
/// On any partial failure every object created so far is torn down before the error returns
/// (no leak) — mirrors [`upload_texture_2d`] / [`create_solid_color_texture`](crate::bindless::create_solid_color_texture).
///
/// # Panics (debug)
/// `debug_assert!`s that `bytes.len() == w * h * bytes_per_pixel(format)` and that `w`/`h`
/// are non-zero.
pub fn upload_texture_2d_raw(
    ctx: &VulkanContext,
    w: u32,
    h: u32,
    bytes: &[u8],
    format: Format,
) -> Result<VulkanTexture, VulkanError> {
    debug_assert!(w > 0 && h > 0, "invariant: texture extent is non-zero");
    let bpp = match format {
        Format::R8Unorm => 1u64,
        Format::R8G8Unorm => 2,
        Format::R8G8B8A8Unorm => 4,
        // SAFETY-adjacent invariant (not `unsafe`): this seam is used only for the boot-time
        // LUT uploads today, all of which are one of the three formats above.
        _ => return Err(VulkanError::Unsupported("upload_texture_2d_raw: unhandled format")),
    };
    debug_assert_eq!(
        bytes.len() as u64,
        (w as u64) * (h as u64) * bpp,
        "invariant: bytes must be exactly w * h * bytes_per_pixel(format)"
    );

    let texture = ctx.create_texture(&TextureDesc {
        width: w,
        height: h,
        depth: 1,
        format,
        dimension: TextureDimension::D2,
        usage: ImageUsage::SAMPLED | ImageUsage::TRANSFER_DST,
        array_layers: 1,
        mip_levels: 1,
        view_format: None,
    })?;

    if let Err(e) = upload_raw_pixels(ctx, &texture, w, h, bytes) {
        // SAFETY: `texture` was just created on `ctx`, owned exclusively here, and the
        // upload's own submit (if any ran) is fence-waited internally before this error
        // could surface; destroy it once on this edge.
        unsafe { ctx.destroy_texture(texture) };
        return Err(e);
    }
    Ok(texture)
}

/// The staged upload + layout-transition submit for [`upload_texture_2d_raw`] — mirrors
/// [`crate::bindless`]'s `upload_solid_pixels` exactly (staging buffer →
/// `copy_buffer_to_image` → UNDEFINED→TRANSFER_DST→SHADER_READ_ONLY barriers → one fenced
/// submit), generalized to a caller-supplied (not repeated-fill) byte buffer.
fn upload_raw_pixels(
    ctx: &VulkanContext,
    texture: &VulkanTexture,
    w: u32,
    h: u32,
    bytes: &[u8],
) -> Result<(), VulkanError> {
    let size = bytes.len() as u64;
    let staging = ctx.create_buffer(&BufferDesc {
        size,
        usage: BufferUsage::TRANSFER_SRC,
        location: MemoryLocation::HostVisibleCoherent,
    })?;
    let Some(dst) = ctx.buffer_mapped_ptr(&staging) else {
        // SAFETY: `staging` was just created, never submitted; destroy it once on this edge.
        unsafe { ctx.destroy_buffer(staging) };
        return Err(VulkanError::Unsupported("staging buffer not host-mapped"));
    };
    // SAFETY: `dst` is the persistently-mapped first byte of the host-coherent staging
    // buffer (exactly `size` bytes, just created); `bytes` is a distinct, non-overlapping
    // allocation of `size` bytes; this is the unique writer before any submission binds the
    // buffer. Host-coherent ⇒ no flush.
    unsafe {
        core::ptr::copy_nonoverlapping(bytes.as_ptr(), dst.as_ptr(), bytes.len());
    }

    let mut encoder = match ctx.create_command_encoder() {
        Ok(e) => e,
        Err(e) => {
            // SAFETY: `staging` was just created, never submitted; destroy once.
            unsafe { ctx.destroy_buffer(staging) };
            return Err(e);
        }
    };
    let fence = match ctx.create_fence(false) {
        Ok(f) => f,
        Err(e) => {
            // SAFETY: `encoder`/`staging` were just created, never submitted; destroy each
            // once.
            unsafe {
                ctx.destroy_command_encoder(encoder);
                ctx.destroy_buffer(staging);
            }
            return Err(e);
        }
    };

    let region = [BufferImageCopy {
        buffer_offset: 0,
        buffer_row_length: 0,
        buffer_image_height: 0,
        aspect: ImageAspect::COLOR,
        mip_level: 0,
        base_array_layer: 0,
        layer_count: 1,
        image_offset_x: 0,
        image_offset_y: 0,
        image_offset_z: 0,
        image_extent_w: w,
        image_extent_h: h,
        image_extent_d: 1,
    }];

    let record = (|| -> Result<(), VulkanError> {
        encoder.begin()?;
        // UNDEFINED → TRANSFER_DST_OPTIMAL (the copy destination).
        encoder.image_barrier(&ImageBarrierDesc {
            texture,
            src_stage: BarrierStage::TOP_OF_PIPE,
            dst_stage: BarrierStage::TRANSFER,
            src_access: BarrierAccess::NONE,
            dst_access: BarrierAccess::TRANSFER_WRITE,
            old_layout: ImageLayout::Undefined,
            new_layout: ImageLayout::TransferDstOptimal,
            range: ImageSubresourceRange::COLOR,
        });
        encoder.copy_buffer_to_image(&staging, texture, ImageLayout::TransferDstOptimal, &region);
        // TRANSFER_DST_OPTIMAL → SHADER_READ_ONLY_OPTIMAL (sample-ready).
        encoder.image_barrier(&ImageBarrierDesc {
            texture,
            src_stage: BarrierStage::TRANSFER,
            dst_stage: BarrierStage::FRAGMENT_SHADER,
            src_access: BarrierAccess::TRANSFER_WRITE,
            dst_access: BarrierAccess::SHADER_READ,
            old_layout: ImageLayout::TransferDstOptimal,
            new_layout: ImageLayout::ShaderReadOnlyOptimal,
            range: ImageSubresourceRange::COLOR,
        });
        encoder.end()?;
        let queue = ctx.rhi_queue();
        queue.submit(&encoder, &fence)?;
        ctx.wait_fence(&fence, u64::MAX)?;
        Ok(())
    })();

    // Tear down the setup-class transients. The submit (if it ran) is fence-waited above.
    // SAFETY: `encoder`/`fence`/`staging` were created on `ctx`; the encoder's only
    // submission (if any) completed (fence-waited above on the Ok path, or never submitted
    // on an error path), and each is moved by value ⇒ destroyed once.
    unsafe {
        ctx.destroy_command_encoder(encoder);
        ctx.destroy_fence(fence);
        ctx.destroy_buffer(staging);
    }
    record
}

/// One GPU-resident, mip-chained, bindless-registered texture asset: the OWNED
/// [`VulkanTexture`] plus the bindless slot it was registered into and the draw-time
/// metadata a future sampling shader needs (`width`, `height`, `mip_levels`).
///
/// `TextureGpu` does NOT implement `Drop`: an RHI [`VulkanTexture`] must be
/// destroyed through the owning [`VulkanContext`] (`destroy_texture`) AFTER the
/// device is idle, which a blind `Drop` cannot guarantee — see [`TextureAssetsExt::destroy`].
pub struct TextureGpu {
    /// The owned device-local image + view(s) (see [`upload_texture_2d`]).
    pub texture: VulkanTexture,
    /// This texture's slot in the world's [`BindlessTextureTable`] (`>= 1`; slot `0`
    /// is the reserved magenta error texture — see
    /// [`BindlessTextureTable::register`](crate::bindless::BindlessTextureTable::register)).
    pub bindless_slot: u32,
    /// Width in texels (mip 0).
    pub width: u32,
    /// Height in texels (mip 0).
    pub height: u32,
    /// The number of mip levels the texture was built with (`>= 1`).
    pub mip_levels: u32,
}

impl Asset for TextureGpu {
    // `TextureGpu` owns a non-`Send` RHI texture, so it cannot satisfy `Asset::Cpu:
    // Send` itself (mirrors `MeshGpu`'s own `Asset::Cpu = MeshData` reasoning).
    // `TextureData` is the `Send`-safe decoded intermediate `PngTextureLoader` produces.
    type Cpu = TextureData;
}

impl TextureGpu {
    /// The [`AssetBacking::register_layout`] drop glue for `TextureGpu` (mirrors
    /// [`MeshGpu::drop_glue`](crate::mesh::MeshGpu)). Device-inert by design: device
    /// teardown is manual, gated on the caller's idle contract, via
    /// [`TextureAssetsExt::destroy`] / [`OrphanedTextureGpu::drain_ready`] — never
    /// from a destructor. This glue only lets Rust's ordinary field-drop glue run
    /// (`VulkanTexture`/integers all have trivial drop), freeing NO device memory.
    ///
    /// # Safety
    /// The caller (`ComponentPool::drop_at` / the terminal `Drop for Assets<TextureGpu>`)
    /// guarantees `ptr` points at a valid, aligned, fully-initialized `TextureGpu`,
    /// exclusively owned, not accessed again after this call — the standard `DropFn`
    /// contract (`boyko_ecs`'s `component_registry::DropFn`).
    unsafe fn drop_glue(ptr: *mut u8) {
        // SAFETY: see this function's own doc — the caller upholds the `DropFn`
        // contract. `drop_in_place` runs `TextureGpu`'s (trivial, field-wise) drop
        // glue exactly once; no device call is made here (see the doc above).
        unsafe { core::ptr::drop_in_place(ptr.cast::<TextureGpu>()) }
    }
}

impl AssetBacking for TextureGpu {
    // Resident asset record: teardown is manual (device-idle-gated), never a bare
    // `Drop` — see `drop_glue`'s doc.
    const NEEDS_TEARDOWN: bool = true;

    fn register_layout() -> ComponentId {
        register_asset_layout::<TextureGpu>(Some(TextureGpu::drop_glue))
    }
}

