//! [`TextureGpu`] — the GPU-resident, mip-chained, bindless-registered texture asset
//! record (textured-PBR campaign rung T2).
//!
//! Mirrors [`MeshGpu`](crate::mesh::MeshGpu) / [`mesh_assets`](crate::mesh_assets)'s
//! shape: [`TextureGpu`] OWNS its RHI
//! [`VulkanTexture`](boyko_rhi_vulkan::texture::VulkanTexture) directly (Principle 0's
//! FFI/GPU exception — the same class as a mesh's vertex/index buffers), so
//! [`Assets<TextureGpu>`](boyko_ecs::ecs::core::asset::Assets) itself IS the GPU-resident
//! table (no separate mirror). The
//! mint/resolve/teardown domain API ([`TextureAssetsExt`]) is attached via an
//! extension trait, exactly as [`MeshAssetsExt`](crate::mesh_assets::MeshAssetsExt).
//!
//! # Live wiring (textured-PBR T6b/T6c/T7)
//!
//! [`Assets<TextureGpu>`](boyko_ecs::ecs::core::asset::Assets) /
//! [`BindlessTextureTable`] are registered as `NonSend`
//! resources by `boyko_app::runner` at boot (T6b); the bindless descriptor set is bound
//! at set 1 by the TEXTURED raster pipeline (T6c, `gbuffer_mrt_tex.{vs,fs}`).
//! [`TextureAssetsExt::register_texture`] / [`build_texture_gpu`] / [`GpuUpload`] for
//! [`TextureGpu`] are the load-time device path a scene's `setup` system drives directly
//! — exercised end to end by `pbr_material_showcase.rs` (T7) and `textured_smoke.rs`, as
//! well as this module's unit tests and the `#[ignore]` GPU smoke test. Teardown retires
//! through
//! [`asset_refcount::retire_deferred_frees`](crate::asset_refcount::retire_deferred_frees)
//! (bindless-slot recycle + [`OrphanedTextureGpu::drain_ready`]).
//!
//! # sRGB via a UNORM image + a mutable sRGB view (Decision D2)
//!
//! `R8G8B8A8_UNORM` optimal-tiling images have MANDATORY `BLIT_SRC`/`BLIT_DST`
//! support; `R8G8B8A8_SRGB` does not guarantee it. So a color-space-sRGB texture
//! (albedo, emissive) is created as UNORM + `VK_IMAGE_CREATE_MUTABLE_FORMAT_BIT`,
//! mip-generated by LINEAR blit on the UNORM image (guaranteed blit support), and
//! SAMPLED through an `R8G8B8A8_SRGB` view (`TextureDesc::view_format`) — the
//! sampler hardware then does sRGB→linear on read. Mip filtering happens in gamma
//! space (the accepted industry-standard tradeoff for a transfer-blit mip chain). A
//! color-space-linear texture (normal, metallic-roughness, AO, ORM) stays UNORM in
//! both image and view. See [`ColorSpace::formats`].

