/// A `Once` latch is PROCESS state, so it is a named module-level `static` rather than one
/// tucked inside the reporter: an observer must be able to reset it, or its green only means
/// "nothing else in this binary tripped this condition first". See `OnceSite::reset`.
pub(crate) static W2206_SITE: OnceSite = OnceSite::new();

/// Reports `boyko-W2206`: a material texture file that EXISTS and could not be decoded.
///
/// **This arm warns and the missing-file arm does not**, which is the whole distinction the two
/// carry. All five folder slots are documented as optional, so an absent map is the normal case
/// and gets an `info!`; a present-but-undecodable one means somebody put a file there intending it
/// to be used, and it silently is not.
///
/// `#[cold]` + `#[inline(never)]`, and a separate function rather than an inline block, for two
/// reasons: it keeps the decode success path free of the emission body, and it gives the observer
/// below something to call — a code whose only emitter is buried inside a function that needs a
/// live `VulkanContext` is a code no unit test can watch.
#[cold]
#[inline(never)]
fn report_material_texture_undecodable(label: &str, path: &Path, err: &impl core::fmt::Display) {
    if W2206_SITE.claim() {
        boyko_log::warn!(
            boyko_log::Render,
            W2206,
            "load_material_folder: {} at {} failed to decode ({}), using the material fallback",
            label,
            boyko_log::dsp!(path.display()),
            boyko_log::dsp!(err)
        );
    }
}

/// Tries each `<dir>/<candidate>` in `candidates`' order (later entries are filename
/// aliases), returning the first `(path, bytes)` pair `read` resolves successfully.
///
/// Pure: `read` is injected so unit tests can exercise the candidate-priority order
/// without touching a real filesystem; the real caller ([`load_material_folder`])
/// passes [`std::fs::read`].
fn resolve_candidate(
    dir: &Path,
    candidates: &[&str],
    mut read: impl FnMut(&Path) -> std::io::Result<Vec<u8>>,
) -> Option<(PathBuf, Vec<u8>)> {
    candidates.iter().find_map(|name| {
        let path = dir.join(name);
        read(&path).ok().map(|bytes| (path, bytes))
    })
}

/// Loads one [`MaterialTextures`] slot from `dir` per `spec`'s candidate/color-space
/// convention, decoding via [`PngTextureLoader::decode`] (the SAME device-upload path
/// a host-authored `.png` asset takes) and registering it into the bindless table.
///
/// Returns the resolved bindless slot, or `0` (the reserved fallback — the material's
/// scalar/vertex data covers this channel) with a one-line [`eprintln!`] note if no
/// candidate file exists, is unreadable, or fails to decode. NEVER panics: a folder
/// convention must render with whatever subset of maps is present.
fn load_slot(
    dir: &Path,
    spec: FolderSlotSpec,
    ctx: &VulkanContext,
    textures: &mut Assets<TextureGpu>,
    bindless: &mut BindlessTextureTable,
) -> u32 {
    let Some((path, bytes)) = resolve_candidate(dir, spec.candidates, |p| std::fs::read(p)) else {
        // `info!`, and NOT a coded `warn!`. Every one of the five folder slots is documented as
        // optional and a missing file is the normal case, so warning here would put a `Warn` in
        // the log of every material that ships four maps instead of five — noise that trains a
        // reader to ignore the level.
        //
        // KNOWN LIMIT, recorded rather than guessed at: this arm also covers an UNREADABLE file,
        // because `resolve_candidate` discards the `io::Error` with `.ok()`. A permissions fault
        // is therefore reported at the same level as an absent optional map. Splitting them means
        // returning the reason from `resolve_candidate` and re-blessing the three tests that pin
        // its `Option` signature; it is in `docs/OPEN-QUESTIONS.md` with that cost, not silently
        // folded into this rung.
        boyko_log::info!(
            boyko_log::Render,
            "load_material_folder: {} not found in {} (tried {}), using the material fallback",
            spec.label,
            boyko_log::dsp!(dir.display()),
            boyko_log::dsp!(format_args!("{:?}", spec.candidates))
        );
        return 0;
    };
    match PngTextureLoader::decode(&bytes) {
        Ok(mut data) => {
            data.color_space = spec.color_space;
            // NORMAL-MAP CONVENTION (owner-set 2026-07-16): this engine's CANONICAL
            // tangent-space normal convention is DIRECTX (green-down: +G = a slope facing
            // image-BOTTOM) -- the Unreal Engine convention. The engine NEVER re-signs a
            // normal map: not here, and not in the TEXTURED shaders (which read the map with
            // no negation). An `assets/materials/<pack>/pbr/normal.png` is REQUIRED to already
            // be DirectX-convention; OpenGL-convention downloads (`*-ogl` vendor files) are
            // converted ONCE, offline, at asset-prep time (`scripts/normal_ogl_to_dx.py`).
            // See that script + `gbuffer_mrt.fs.hlsl`'s GREEN-CHANNEL CONVENTION block.
            let handle = textures.register_texture(ctx, bindless, &data);
            let slot = textures.texture(handle).bindless_slot;
            // The one `println!` in this crate, and the only site in the whole L8a set that wrote
            // to STDOUT rather than stderr. It is a lifecycle fact with no condition behind it,
            // so by Decision 7 it carries no code.
            boyko_log::info!(
                boyko_log::Render,
                "load_material_folder: loaded {} <- {}",
                spec.label,
                boyko_log::dsp!(path.display())
            );
            slot
        }
        Err(e) => {
            report_material_texture_undecodable(spec.label, &path, &e);
            0
        }
    }
}

/// Loads the standard PBR texture-folder convention (textured-PBR rung T7) from `dir`,
/// uploading + bindless-registering whichever of the five slot files are present, and
/// returns the assembled [`MaterialTextures`] sidecar (pass it to
/// [`Material::with_textures`](crate::material::Material::with_textures)).
///
/// # Filenames (all optional — a missing file falls back gracefully, never panics)
///
/// | slot          | candidates (later = alias)          | color space                        |
/// |---------------|--------------------------------------|-------------------------------------|
/// | albedo        | `albedo.png`, `base_color.png`       | sRGB                                |
/// | normal        | `normal.png`                          | linear, tangent-space               |
/// | metal_rough   | `metallic_roughness.png`, `mr.png`   | linear, glTF ORM (G=rough, B=metal) |
/// | ao            | `ao.png`                              | linear, R=occlusion                 |
/// | emissive      | `emissive.png`                        | sRGB                                |
///
/// A missing, unreadable, or undecodable file for a given slot leaves that slot `0`
/// (the material's scalar/vertex-color fallback for that channel) and prints a
/// one-line [`eprintln!`] note — this fn never panics on a partial or empty folder.
/// Each file is decoded via [`PngTextureLoader::decode`] — the SAME device-upload
/// path a host-authored `.png` asset takes — with [`TextureData::color_space`]
/// overridden per-slot (the loader itself has no per-material-slot context).
pub fn load_material_folder(
    textures: &mut Assets<TextureGpu>,
    ctx: &VulkanContext,
    bindless: &mut BindlessTextureTable,
    dir: &Path,
) -> MaterialTextures {
    MaterialTextures {
        albedo: load_slot(dir, FOLDER_SLOT_ALBEDO, ctx, textures, bindless),
        normal: load_slot(dir, FOLDER_SLOT_NORMAL, ctx, textures, bindless),
        metal_rough: load_slot(dir, FOLDER_SLOT_METAL_ROUGH, ctx, textures, bindless),
        ao: load_slot(dir, FOLDER_SLOT_AO, ctx, textures, bindless),
        emissive: load_slot(dir, FOLDER_SLOT_EMISSIVE, ctx, textures, bindless),
    }
}

/// Fill-reject `TextureGpu` values awaiting the fence-gated device-free pass
/// (mirrors [`OrphanedMeshGpu`](crate::mesh_assets::OrphanedMeshGpu) — the F6
/// Decision-4 sibling for the texture asset table).
///
/// `Assets::fill`'s `Err((_, TextureGpu))` arm returns a value the store never took
/// ownership of (a stale/double-fill target) — it still holds a LIVE device image
/// (and a live bindless slot) with no `Drop` to free them. This dedicated `!Send`
/// [`NonSendResource`] is the only correct home — see
/// [`OrphanedMeshGpu`](crate::mesh_assets::OrphanedMeshGpu)'s doc for the full
/// argument (identical here, `TextureGpu` in place of `MeshGpu`).
#[derive(Default)]
pub struct OrphanedTextureGpu {
    orphans: Vec<(TextureGpu, u64)>,
}

impl NonSendResource for OrphanedTextureGpu {}

impl OrphanedTextureGpu {
    /// Queues a fill-rejected `TextureGpu` value for teardown once every submit
    /// that could reference it is fence-complete. `retire_frame` is the
    /// caller-computed gate (`RenderEpoch` at reject time `+ RETIRE_DELAY`) —
    /// strictly conservative (a value `fill` rejected was never submitted at all,
    /// mirrors [`OrphanedMeshGpu::push`](crate::mesh_assets::OrphanedMeshGpu::push)'s
    /// proof).
    #[inline]
    pub fn push(&mut self, texture: TextureGpu, retire_frame: u64) {
        self.orphans.push((texture, retire_frame));
    }

    /// `true` if no orphan is awaiting teardown — the O(1) golden early-out (no
    /// `fill` caller exists in-tree yet, so this is always `true` today).
    #[inline]
    pub fn is_empty(&self) -> bool {
        self.orphans.is_empty()
    }

    /// Tears down (bindless slot unregister, then the RHI image) every orphan whose
    /// `retire_frame <= epoch`, retaining the rest in enqueue order. Called ONLY by
    /// the host's per-frame F6-style retire step AFTER `wait_frame_in_flight` for
    /// this `epoch` — the same per-resource fence precondition every other F6
    /// destroy call relies on (mirrors
    /// [`OrphanedMeshGpu::drain_ready`](crate::mesh_assets::OrphanedMeshGpu::drain_ready)).
    pub fn drain_ready(&mut self, epoch: u64, ctx: &VulkanContext, aux: &mut BindlessTextureTable) {
        let mut i = 0;
        while i < self.orphans.len() {
            if self.orphans[i].1 > epoch {
                i += 1;
                continue;
            }
            let (record, _) = self.orphans.remove(i);
            // Stage the slot at the SAME `epoch` gate this orphan itself just cleared
            // — the value was never submitted (F6 design proof C), so its bindless
            // write is also never read by any in-flight command buffer.
            aux.unregister(record.bindless_slot, epoch);
            // SAFETY: `record.texture` was created by the failed upload attempt on
            // this same `ctx`; the value was never submitted (see above), so no GPU
            // work references it; the by-value move destroys it exactly once.
            unsafe { ctx.destroy_texture(record.texture) };
        }
    }
}

