/// The device work behind [`TextureAssetsExt::register_texture`]: uploads a
/// mip-chained texture per `data` ([`ColorSpace::formats`] picks the image/view
/// format, [`mip_levels_for`] picks the mip count), registers it into `aux`'s
/// bindless table, and returns the assembled [`TextureGpu`] (NOT yet inserted into
/// any [`Assets<TextureGpu>`] table — the caller mints the row).
///
/// Factored out of [`TextureAssetsExt::register_texture`] (mirrors
/// [`build_mesh_gpu`](crate::mesh_assets::build_mesh_gpu)) so a loaded texture's
/// GPU-upload pass ([`GpuUpload`](crate::gpu_upload::GpuUpload) for [`TextureGpu`])
/// runs through the EXACT SAME device path a host-authored `register_texture` call
/// uses.
///
/// # Panics
/// Panics (`expect`) if the texture upload fails — a device out-of-memory at
/// asset-registration time is a setup failure, not a recoverable per-frame error
/// (mirrors [`build_mesh_gpu`](crate::mesh_assets::build_mesh_gpu)'s contract).
pub fn build_texture_gpu(
    ctx: &VulkanContext,
    aux: &mut BindlessTextureTable,
    data: &TextureData,
) -> TextureGpu {
    let (format, view_format) = data.color_space.formats();
    let mip_levels = mip_levels_for(data.width, data.height);
    let texture = upload_texture_2d(ctx, data.width, data.height, &data.rgba8, format, view_format, mip_levels)
        .expect("invariant: texture upload (setup stage)");
    let bindless_slot = aux.register(ctx, texture.view());
    TextureGpu {
        texture,
        bindless_slot,
        width: data.width,
        height: data.height,
        mip_levels,
    }
}

/// The texture-domain API over the world's [`Assets<TextureGpu>`] table
/// (textured-PBR T2), mirroring [`MeshAssetsExt`](crate::mesh_assets::MeshAssetsExt).
///
/// Unlike [`MeshHandle`](boyko_scene::render_caps::MeshHandle) (a bespoke dense
/// `u32` render carrier), texture resolution uses [`Handle<TextureGpu>`] directly —
/// no per-entity render-cap component references a texture yet (T5/T6), so there is
/// no existing dense-carrier consumer to mirror `MeshHandle`'s truncation shape for.
pub trait TextureAssetsExt {
    /// Uploads `data` into a fresh, mip-chained, bindless-registered GPU texture and
    /// returns its handle.
    ///
    /// # Bindless-slot exhaustion
    /// If `aux`'s bindless table is exhausted (every real slot in use or awaiting its
    /// fence horizon — practically unreachable at
    /// [`BINDLESS_TEXTURE_CAPACITY`](boyko_rhi_vulkan::bindless::BINDLESS_TEXTURE_CAPACITY)),
    /// [`BindlessTextureTable::register`] `debug_assert!`s (a dev-build invariant
    /// violation) and, in release, `eprintln!`s a warning and silently aliases the
    /// reserved slot 0 (the magenta error texture) instead of an out-of-range write —
    /// the returned [`TextureGpu`] resolves through that slot, so the material renders
    /// visibly wrong (magenta) rather than corrupting memory.
    ///
    /// # Panics
    /// Same contract as [`build_texture_gpu`]: a device out-of-memory at
    /// asset-registration time is a setup failure.
    fn register_texture(
        &mut self,
        ctx: &VulkanContext,
        aux: &mut BindlessTextureTable,
        data: &TextureData,
    ) -> Handle<TextureGpu>;

    /// Resolves a [`Handle<TextureGpu>`] to its GPU asset, or `None` if the handle is
    /// stale / out of range / never registered.
    fn try_get(&self, h: Handle<TextureGpu>) -> Option<&TextureGpu>;

    /// Resolves a [`Handle<TextureGpu>`] to its GPU asset.
    ///
    /// # Panics
    /// Panics if `h` does not resolve — a handle no live row resolves to is a
    /// caller/asset-binding bug, not a recoverable error.
    fn texture(&self, h: Handle<TextureGpu>) -> &TextureGpu;

    /// Destroys every registered texture's RHI image through `ctx` and its bindless
    /// slot through `aux`, then empties the table.
    ///
    /// # Safety
    /// The caller MUST have made the device idle (e.g. via the renderer's `Drop` /
    /// `wait_idle`) so no in-flight submit still references any texture or the
    /// bindless set; each is destroyed/unregistered exactly once. Mirrors
    /// [`MeshAssetsExt::destroy`](crate::mesh_assets::MeshAssetsExt::destroy).
    unsafe fn destroy(&mut self, ctx: &VulkanContext, aux: &mut BindlessTextureTable);
}

impl TextureAssetsExt for Assets<TextureGpu> {
    fn register_texture(
        &mut self,
        ctx: &VulkanContext,
        aux: &mut BindlessTextureTable,
        data: &TextureData,
    ) -> Handle<TextureGpu> {
        let gpu = build_texture_gpu(ctx, aux, data);
        self.add(gpu)
    }

    #[inline]
    fn try_get(&self, h: Handle<TextureGpu>) -> Option<&TextureGpu> {
        self.get(h)
    }

    #[inline]
    fn texture(&self, h: Handle<TextureGpu>) -> &TextureGpu {
        self.try_get(h)
            .expect("invariant: Handle<TextureGpu> resolves to a registered texture")
    }

    unsafe fn destroy(&mut self, ctx: &VulkanContext, aux: &mut BindlessTextureTable) {
        // `Assets<T>` exposes no owned/mutable whole-table iteration (only the
        // borrowed `iter()` and the handle-keyed `remove()`), so every live handle is
        // collected FIRST (a small, one-shot teardown allocation — never on the
        // gameplay hot path, Principle 5's actual scope) and then removed by value,
        // one texture at a time (mirrors `MeshAssetsExt::destroy`).
        let handles: Vec<Handle<TextureGpu>> = self.iter().map(|(h, _)| h).collect();
        for h in handles {
            let record = self
                .remove(h)
                .expect("invariant: a handle collected from iter() resolves via remove()");
            // The device is idle (caller contract), so the slot's fence horizon is
            // moot — return it to the free list immediately (epoch 0) rather than
            // stage it, mirroring a hard/full-teardown recycle.
            aux.unregister(record.bindless_slot, 0);
            // SAFETY: `record.texture` was created by `build_texture_gpu` on this
            // same `ctx`; the device is idle (caller contract), so no submit
            // references it; the by-value move destroys it exactly once.
            unsafe { ctx.destroy_texture(record.texture) };
        }
    }
}

